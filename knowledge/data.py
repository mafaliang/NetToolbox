def search(keyword: str) -> list[dict]:
    """按标题 / 标签 / 正文检索知识条目。"""
    kw = (keyword or "").strip().lower()
    if not kw:
        return list(KNOWLEDGE)
    result = []
    for item in KNOWLEDGE:
        haystack = " ".join([
            item["title"], item["category"], item["tags"], item["content"]
        ]).lower()
        if kw in haystack:
            result.append(item)
    return result
